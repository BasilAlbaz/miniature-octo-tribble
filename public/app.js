function startSession(questionIds) {
  let selected = questionIds
    ? questionIds.map((id) => questions.find((question) => question.id === id)).filter(Boolean)
    : getFilteredQuestions();
  if (!questionIds && qbankSettings.order === "mixed") selected = [...selected].sort(() => Math.random() - 0.5);
  const limit = questionIds ? selected.length : Math.max(1, Number(qbankSettings.count) || 5);
  selected = selected.slice(0, limit);
  if (!selected.length) {
    showToast(t("noMatchingQuestions"));
    return;
  }
  const duration = Math.max(5, selected.length * 90);
  state.activeSession = {
    id: makeId(),
    questionIds: selected.map((item) => item.id),
    index: 0,
    mode: qbankSettings.mode,
    answers: {},
    startedAt: Date.now(),
    deadline: qbankSettings.mode === "timed" ? Date.now() + duration * 1000 : null,
    finished: false
  };
  selectedAnswer = null;
  typedAnswer = "";
  writtenRating = null;
  currentRoute = "qbank";
  persist();
  render();
  startSessionTimer();
}

function startSessionTimer() {
  clearInterval(sessionTimer);
  sessionTimer = null;
  const session = state.activeSession;
  if (!session || session.mode !== "timed" || session.finished) return;
  sessionTimer = setInterval(() => {
    const clock = $("#session-clock");
    if (!clock) return;
    clock.textContent = getClockLabel(session.deadline);
    if (session.deadline <= Date.now()) finishSession(true);
  }, 1000);
}

function submitCurrentAnswer(correct) {
  const session = state.activeSession;
  const question = questions.find((item) => item.id === session?.questionIds[session.index]);
  if (!session || !question || session.answers[question.id]) return;
  const isCorrect = Boolean(correct);
  session.answers[question.id] = {
    correct: isCorrect,
    selected: question.type === "mcq" ? selectedAnswer : null,
    response: question.type === "written" ? typedAnswer : null
  };
  const previous = state.tracker[question.id] || { attempts: 0, correct: 0, flagged: false };
  state.tracker[question.id] = {
    attempts: previous.attempts + 1,
    correct: previous.correct + (isCorrect ? 1 : 0),
    firstCorrect: previous.attempts === 0 ? isCorrect : previous.firstCorrect,
    status: isCorrect ? "correct" : "wrong",
    flagged: previous.flagged,
    updatedAt: new Date().toISOString()
  };
  persist();
  render();
}

function nextQuestion() {
  const session = state.activeSession;
  if (!session) return;
  selectedAnswer = null;
  typedAnswer = "";
  writtenRating = null;
  if (session.index + 1 >= session.questionIds.length) {
    finishSession(false);
    return;
  }
  session.index += 1;
  persist();
  render();
}

function finishSession(timedOut) {
  const session = state.activeSession;
  if (!session || session.finished) return;
  if (timedOut) {
    for (const id of session.questionIds) {
      if (!session.answers[id]) {
        session.answers[id] = { correct: false, selected: null, response: null };
        const previous = state.tracker[id] || { attempts: 0, correct: 0, flagged: false };
        state.tracker[id] = { attempts: previous.attempts + 1, correct: previous.correct, status: "wrong", flagged: previous.flagged };
      }
    }
  }
  session.finished = true;
  session.timedOut = timedOut;
  const total = session.questionIds.length;
  const correct = Object.values(session.answers).filter((answer) => answer.correct).length;
  const minutes = Math.max(1, Math.round((Date.now() - session.startedAt) / 60000));
  state.history.push({ id: session.id || makeId(), date: todayKey(), total, correct, minutes, mode: session.mode, questionIds: [...session.questionIds] });
  persist();
  clearInterval(sessionTimer);
  sessionTimer = null;
  selectedAnswer = null;
  typedAnswer = "";
  render();
  if (timedOut) showToast(t("noTime"));
}

