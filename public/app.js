document.addEventListener("keydown", (event) => {
  if ($("#modal-backdrop") && !$("#modal-backdrop").hidden) return;
  if (event.target.matches("input, textarea, select, [contenteditable='true']")) return;
  if (event.ctrlKey || event.metaKey || event.altKey) return;
  const key = event.key.toLowerCase();
  const keys = state.preferences.shortcuts || {};
  const routeFor = { dashboard: "dashboard", qbank: "qbank", library: "library" };
  const sequence = `${shortcutPrefix} ${key}`.trim();
  const matched = Object.entries(keys).find(([, binding]) => String(binding).toLowerCase() === sequence);
  if (matched) {
    event.preventDefault();
    shortcutPrefix = "";
    if (matched[0] === "help") {
      settingsCategory = "shortcuts";
      navigate("settings");
    } else if (routeFor[matched[0]]) navigate(routeFor[matched[0]]);
    return;
  }
  const prefixes = Object.values(keys).map((binding) => String(binding).toLowerCase().split(" ")[0]);
  if (prefixes.includes(key)) {
    shortcutPrefix = key;
    clearTimeout(shortcutPrefixTimer);
    shortcutPrefixTimer = setTimeout(() => { shortcutPrefix = ""; }, 1400);
  } else {
    shortcutPrefix = "";
  }
});

