function getTodayStats() {
  const today = todayKey();
  return state.history.filter((entry) => entry.date === today).reduce((acc, entry) => {
    acc.answered += entry.total;
    acc.correct += entry.correct;
    return acc;
  }, { answered: 0, correct: 0 });
}

function getSummary() {
  const sessions = state.history.length;
  const answered = state.history.reduce((sum, item) => sum + item.total, 0);
  const correct = state.history.reduce((sum, item) => sum + item.correct, 0);
  const streakDates = [...new Set(state.history.map((item) => item.date))].sort().reverse();
  let streak = 0;
  let date = new Date();
  if (streakDates[0] !== todayKey()) date.setDate(date.getDate() - 1);
  for (const day of streakDates) {
    if (day !== dateKey(date)) break;
    streak += 1;
    date.setDate(date.getDate() - 1);
  }
  const flagged = Object.values(state.tracker).filter((item) => item.flagged).length;
  const saved = state.savedArticles.length + flagged;
  const todayStats = getTodayStats();
  return {
    sessions,
    answered,
    accuracy: answered ? Math.round((correct / answered) * 100) : 0,
    minutes: state.history.reduce((sum, item) => sum + item.minutes, 0),
    streak,
    saved,
    today: todayStats.answered
  };
}

