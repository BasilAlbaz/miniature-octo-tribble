function mergeBackup(incoming) {
  const localTimestamp = Date.parse(state.updatedAt || 0) || 0;
  const remoteTimestamp = Date.parse(incoming.updatedAt || 0) || 0;
  const latestState = remoteTimestamp > localTimestamp ? incoming : state;
  const olderState = latestState === incoming ? state : incoming;
  const historyMap = new Map();
  for (const entry of [...(state.history || []), ...(incoming.history || [])]) {
    if (!entry || typeof entry !== "object") continue;
    const id = String(entry.id || `${entry.date}:${entry.total}:${entry.correct}:${entry.minutes}`);
    const existing = historyMap.get(id);
    if (!existing || (Date.parse(entry.updatedAt || entry.date || 0) || 0) > (Date.parse(existing.updatedAt || existing.date || 0) || 0)) historyMap.set(id, { ...entry, id });
  }
  const tracker = { ...(olderState.tracker || {}) };
  for (const [id, record] of Object.entries(latestState.tracker || {})) {
    const prior = tracker[id];
    const recordTimestamp = Date.parse(record.updatedAt || 0) || 0;
    const priorTimestamp = Date.parse(prior?.updatedAt || 0) || 0;
    if (!prior || recordTimestamp >= priorTimestamp || record.attempts > prior.attempts) tracker[id] = record;
  }
  const notes = new Map();
  for (const note of [...(state.notes || []), ...(incoming.notes || [])]) {
    if (!note || typeof note.id !== "string") continue;
    const existing = notes.get(note.id);
    const timestamp = Date.parse(note.updatedAt || note.createdAt || 0) || 0;
    const existingTimestamp = Date.parse(existing?.updatedAt || existing?.createdAt || 0) || 0;
    if (!existing || timestamp >= existingTimestamp) notes.set(note.id, note);
  }
  state = {
    ...state,
    ...latestState,
    tracker,
    history: [...historyMap.values()].sort((a, b) => String(a.date).localeCompare(String(b.date))),
    notes: [...notes.values()],
    dismissedQuestions: [...new Set([...(state.dismissedQuestions || []), ...(incoming.dismissedQuestions || [])])],
    savedArticles: [...new Set([...(state.savedArticles || []), ...(incoming.savedArticles || [])])],
    offlineArticles: [...new Set([...(state.offlineArticles || []), ...(incoming.offlineArticles || [])])],
    offlinePacks: [...new Set([...(state.offlinePacks || []), ...(incoming.offlinePacks || [])])],
    completedVideos: [...new Set([...(state.completedVideos || []), ...(incoming.completedVideos || [])])],
    achievements: [...new Set([...(state.achievements || []), ...(incoming.achievements || [])])]
  };
  persist();
}

function sanitizeBackupState(source) {
  const safe = defaultState();
  if (!source || typeof source !== "object" || Array.isArray(source)) return null;
  safe.lang = source.lang === "en" ? "en" : "ar";
  safe.contentLanguage = ["auto", "ar", "en", "both"].includes(source.contentLanguage) ? source.contentLanguage : "auto";
  safe.theme = ["system", "light", "dark"].includes(source.theme) ? source.theme : "light";
  safe.accent = ["green", "blue", "violet", "rose"].includes(source.accent) ? source.accent : "green";
  safe.density = source.density === "compact" ? "compact" : "comfortable";
  safe.frosted = Boolean(source.frosted);
  safe.transitions = source.transitions !== false;
  safe.name = typeof source.name === "string" ? source.name.slice(0, 36) : "";
  safe.goal = Number.isInteger(Number(source.goal)) ? Math.max(1, Math.min(500, Number(source.goal))) : 10;
  const preferences = source.preferences && typeof source.preferences === "object" ? source.preferences : {};
  safe.preferences = {
    ...safe.preferences,
    assistantModel: ["fast", "balanced", "detailed"].includes(preferences.assistantModel) ? preferences.assistantModel : "balanced",
    responseWait: [10, 20, 30, 45].includes(Number(preferences.responseWait)) ? Number(preferences.responseWait) : 20,
    osceVoice: Boolean(preferences.osceVoice),
    liveTranscript: preferences.liveTranscript !== false,
    voiceRate: Number.isFinite(Number(preferences.voiceRate)) ? Math.max(.75, Math.min(1.5, Number(preferences.voiceRate))) : 1,
    haptics: Boolean(preferences.haptics),
    keepAwake: Boolean(preferences.keepAwake),
    shortcuts: {
      dashboard: typeof preferences.shortcuts?.dashboard === "string" ? preferences.shortcuts.dashboard.slice(0, 12) : "g d",
      qbank: typeof preferences.shortcuts?.qbank === "string" ? preferences.shortcuts.qbank.slice(0, 12) : "g q",
      library: typeof preferences.shortcuts?.library === "string" ? preferences.shortcuts.library.slice(0, 12) : "g l",
      help: typeof preferences.shortcuts?.help === "string" ? preferences.shortcuts.help.slice(0, 12) : "?"
    }
  };
  if (source.tracker && typeof source.tracker === "object" && !Array.isArray(source.tracker)) {
    safe.tracker = Object.fromEntries(Object.entries(source.tracker)
      .filter(([id, entry]) => questions.some((question) => question.id === id) && entry && typeof entry === "object")
      .map(([id, entry]) => [id, {
        attempts: Math.max(0, Math.min(10000, Number(entry.attempts) || 0)),
        correct: Math.max(0, Math.min(10000, Number(entry.correct) || 0)),
        firstCorrect: Boolean(entry.firstCorrect),
        status: ["correct", "wrong", "new"].includes(entry.status) ? entry.status : "new",
        flagged: Boolean(entry.flagged),
        updatedAt: typeof entry.updatedAt === "string" ? entry.updatedAt.slice(0, 40) : ""
      }]));
  }
  safe.history = Array.isArray(source.history) ? source.history.slice(-1000).filter((entry) => entry && typeof entry === "object" && /^\d{4}-\d{2}-\d{2}$/.test(entry.date)).map((entry) => ({
    id: typeof entry.id === "string" ? entry.id.slice(0, 100) : makeId(),
    date: entry.date,
    total: Math.max(0, Math.min(500, Number(entry.total) || 0)),
    correct: Math.max(0, Math.min(500, Number(entry.correct) || 0)),
    minutes: Math.max(0, Math.min(100000, Number(entry.minutes) || 0)),
    mode: entry.mode === "timed" ? "timed" : "tutor"
  })) : [];
  safe.dismissedQuestions = Array.isArray(source.dismissedQuestions) ? source.dismissedQuestions.filter((id) => questions.some((question) => question.id === id)) : [];
  safe.notes = Array.isArray(source.notes) ? source.notes.slice(-500).filter((note) => note && typeof note.id === "string").map((note) => ({
    id: note.id.slice(0, 100),
    title: typeof note.title === "string" ? note.title.slice(0, 100) : "",
    body: typeof note.body === "string" ? note.body.slice(0, 5000) : "",
    createdAt: typeof note.createdAt === "string" ? note.createdAt.slice(0, 40) : new Date().toISOString(),
    updatedAt: typeof note.updatedAt === "string" ? note.updatedAt.slice(0, 40) : new Date().toISOString()
  })) : [];
  safe.reports = Array.isArray(source.reports) ? source.reports.slice(-100).filter((item) => item && typeof item.id === "string").map((item) => ({
    id: item.id.slice(0, 100),
    category: ["bug", "idea", "question"].includes(item.category) ? item.category : "question",
    subject: typeof item.subject === "string" ? item.subject.slice(0, 120) : "",
    description: typeof item.description === "string" ? item.description.slice(0, 4000) : "",
    createdAt: typeof item.createdAt === "string" ? item.createdAt.slice(0, 40) : new Date().toISOString()
  })) : [];
  safe.savedArticles = Array.isArray(source.savedArticles) ? source.savedArticles.filter((id) => articles.some((item) => item.id === id)) : [];
  safe.offlineArticles = Array.isArray(source.offlineArticles) ? source.offlineArticles.filter((id) => articles.some((item) => item.id === id)) : [];
  safe.offlinePacks = Array.isArray(source.offlinePacks) ? source.offlinePacks.filter((id) =>
    ["foundations", "cardio", "clinical"].includes(id) ||
    offlinePackCatalog.some((pack) => pack.id === id) ||
    questionPacks.some((pack) => pack.id === id)
  ) : [];
  safe.completedVideos = Array.isArray(source.completedVideos) ? source.completedVideos.filter((id) => videos.some((item) => item.id === id)) : [];
  safe.cardRatings = Object.fromEntries(Object.keys(safe.cardRatings).map((key) => [key, Math.max(0, Math.min(10000, Number(source.cardRatings?.[key]) || 0))]));
  safe.osceChecks = Array.isArray(source.osceChecks) ? source.osceChecks.filter((index) => Number.isInteger(index) && index >= 0 && index < osceChecklist.length) : [];
  safe.achievements = Array.isArray(source.achievements) ? source.achievements.filter((id) => achievementCatalog.some(([key]) => key === id)) : [];
  safe.updatedAt = typeof source.updatedAt === "string" && Number.isFinite(Date.parse(source.updatedAt)) ? source.updatedAt : new Date(0).toISOString();
  return safe;
}

async function importBackup() {
  const file = $("#backup-file")?.files?.[0];
  if (!file) {
    showToast(t("backupInvalid"));
    return;
  }
  if (file.size > 2 * 1024 * 1024) {
    showToast(t("backupLimit"));
    return;
  }
  try {
    const backup = JSON.parse(await file.text());
    if (backup.format !== "namaa-osler-backup" || backup.version !== 1 || !backup.state || typeof backup.state !== "object") {
      showToast(t("backupInvalid"));
      return;
    }
    const safeState = sanitizeBackupState(backup.state);
    if (!safeState) {
      showToast(t("backupInvalid"));
      return;
    }
    mergeBackup(safeState);
    $("#modal-backdrop").hidden = true;
    render();
    showToast(t("backupImported"));
  } catch (error) {
    console.warn("Could not import the selected demo backup.", error);
    showToast(t("backupInvalid"));
  }
}

